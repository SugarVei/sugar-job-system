import { build } from 'esbuild';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
for (const name of ['mail-interview-sync', 'mailbox-fetch']) {
  await build({
    entryPoints: [resolve(root, 'server', `${name}.ts`)],
    outfile: resolve(root, 'api', `${name}.js`),
    bundle: true,
    // Bundle the sanitizer's ESM parser with its CommonJS entry so the
    // Vercel loader never has to require htmlparser2 as an ES module.
    external: ['@supabase/supabase-js', 'imapflow', 'mailparser', 'luxon'],
    platform: 'node',
    format: 'esm',
    target: 'node22',
    sourcemap: false,
    banner: { js: '// Generated by scripts/build-mail-sync.mjs from server/ sources. Do not edit directly.\nimport { createRequire as createMailSyncRequire } from "node:module";\nconst require = createMailSyncRequire(import.meta.url);' },
  });
  // Run from a native ES module; node -e otherwise hides missing require shims.
  const entry = await import(pathToFileURL(resolve(root, 'api', `${name}.js`)).href);
  if (typeof entry.default !== 'function') throw new Error(`${name}: missing API handler`);
}
