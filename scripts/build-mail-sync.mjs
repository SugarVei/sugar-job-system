import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
for (const name of ['mail-interview-sync', 'mailbox-fetch']) {
  await build({
    entryPoints: [resolve(root, 'server', `${name}.ts`)],
    outfile: resolve(root, 'api', `${name}.js`),
    bundle: true,
    packages: 'external',
    platform: 'node',
    format: 'esm',
    target: 'node22',
    sourcemap: false,
    banner: { js: '// Generated by scripts/build-mail-sync.mjs from server/ sources. Do not edit directly.' },
  });
}
